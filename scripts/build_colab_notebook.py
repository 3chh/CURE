                "# 2. Định nghĩa Kiến Trúc Mô Hình & Hàm Huấn Luyện Chuẩn\n",
                "import math, time, os, zipfile\n",
                "import torch.nn as nn\n",
                "import torch.optim as optim\n",
                "from torchvision import datasets, transforms\n",
                "from torch.utils.data import DataLoader\n",
                "\n",
                "class Block(nn.Module):\n",
                "    def __init__(self, in_planes, out_planes, expansion, stride):\n",
                "        super().__init__()\n",
                "        self.stride = stride\n",
                "        planes = expansion * in_planes\n",
                "        self.conv1 = nn.Conv2d(in_planes, planes, 1, 1, 0, bias=False)\n",
                "        self.bn1 = nn.BatchNorm2d(planes)\n",
                "        self.conv2 = nn.Conv2d(planes, planes, 3, stride, 1, groups=planes, bias=False)\n",
                "        self.bn2 = nn.BatchNorm2d(planes)\n",
                "        self.conv3 = nn.Conv2d(planes, out_planes, 1, 1, 0, bias=False)\n",
                "        self.bn3 = nn.BatchNorm2d(out_planes)\n",
                "        self.shortcut = nn.Sequential()\n",
                "        if stride == 1 and in_planes != out_planes:\n",
                "            self.shortcut = nn.Sequential(nn.Conv2d(in_planes, out_planes, 1, 1, 0, bias=False), nn.BatchNorm2d(out_planes))\n",
                "\n",
                "    def forward(self, x):\n",
                "        out = nn.functional.relu(self.bn1(self.conv1(x)))\n",
                "        out = nn.functional.relu(self.bn2(self.conv2(out)))\n",
                "        out = self.bn3(self.conv3(out))\n",
                "        out = out + self.shortcut(x) if self.stride == 1 else out\n",
                "        return out\n",
                "\n",
                "class MobileNetV2_32x32(nn.Module):\n",
                "    CFG = ((1, 16, 1, 1), (6, 24, 2, 1), (6, 32, 3, 2), (6, 64, 4, 2), (6, 96, 3, 1), (6, 160, 3, 2), (6, 320, 1, 1))\n",
                "    def __init__(self, num_classes=10):\n",
                "        super().__init__()\n",
                "        self.conv1 = nn.Conv2d(3, 32, 3, 1, 1, bias=False)\n",
                "        self.bn1 = nn.BatchNorm2d(32)\n",
                "        layers = []\n",
                "        in_planes = 32\n",
                "        for exp, out, nb, strd in self.CFG:\n",
                "            strides = [strd] + [1] * (nb - 1)\n",
                "            for s in strides:\n",
                "                layers.append(Block(in_planes, out, exp, s))\n",
                "                in_planes = out\n",
                "        self.layers = nn.Sequential(*layers)\n",
                "        self.conv2 = nn.Conv2d(320, 1280, 1, 1, 0, bias=False)\n",
                "        self.bn2 = nn.BatchNorm2d(1280)\n",
                "        self.pool = nn.AdaptiveAvgPool2d((1, 1))\n",
                "        self.fc = nn.Linear(1280, num_classes)\n",
                "\n",
                "    def forward(self, x):\n",
                "        out = nn.functional.relu(self.bn1(self.conv1(x)))\n",
                "        out = self.layers(out)\n",
                "        out = nn.functional.relu(self.bn2(self.conv2(out)))\n",
                "        feat = self.pool(out).flatten(1)\n",
                "        logits = self.fc(feat)\n",
                "        return logits\n",
                "\n",
                "def train_model(model_cls, name, seed, epochs=100, batch_size=128, lr=0.1):\n",
                "    print(f'\\n========================================\\nBẮT ĐẦU HUẤN LUYỆN: {name} (Seed {seed}) - {epochs} EPOCHS\\n========================================')\n",
                "    torch.manual_seed(seed)\n",
                "    torch.cuda.manual_seed_all(seed)\n",
                "    \n",
                "    transform_train = transforms.Compose([\n",
                "        transforms.RandomCrop(32, padding=4),\n",
                "        transforms.RandomHorizontalFlip(),\n",
                "        transforms.ToTensor(),\n",
                "        transforms.Normalize((0.4914, 0.4822, 0.4465), (0.2470, 0.2435, 0.2616)),\n",
                "    ])\n",
                "    transform_test = transforms.Compose([\n",
                "        transforms.ToTensor(),\n",
                "        transforms.Normalize((0.4914, 0.4822, 0.4465), (0.2470, 0.2435, 0.2616)),\n",
                "    ])\n",
                "    \n",
                "    trainset = datasets.CIFAR10(root='./data', train=True, download=True, transform=transform_train)\n",
                "    testset = datasets.CIFAR10(root='./data', train=False, download=True, transform=transform_test)\n",
                "    trainloader = DataLoader(trainset, batch_size=batch_size, shuffle=True, num_workers=2, pin_memory=True)\n",
                "    testloader = DataLoader(testset, batch_size=batch_size, shuffle=False, num_workers=2)\n",
                "    \n",
                "    model = model_cls(num_classes=10).cuda()\n",
                "    criterion = nn.CrossEntropyLoss()\n",
                "    optimizer = optim.SGD(model.parameters(), lr=lr, momentum=0.9, weight_decay=5e-4, nesterov=True)\n",
                "    scheduler = optim.lr_scheduler.CosineAnnealingLR(optimizer, T_max=epochs, eta_min=1e-6)\n",
                "    scaler = torch.cuda.amp.GradScaler()\n",
                "    \n",
                "    best_acc = 0.0\n",
                "    best_ckpt = f'best_{name}.ckpt'\n",
                "    t0 = time.time()\n",
                "    \n",
                "    for epoch in range(1, epochs + 1):\n",
                "        model.train()\n",
                "        train_loss = 0.0\n",
                "        for inputs, targets in trainloader:\n",
                "            inputs, targets = inputs.cuda(), targets.cuda()\n",
                "            optimizer.zero_grad()\n",
                "            with torch.cuda.amp.autocast():\n",
