                "                loss = criterion(outputs, targets)\n",
                "            scaler.scale(loss).backward()\n",
                "            scaler.step(optimizer)\n",
                "            scaler.update()\n",
                "            train_loss += loss.item() * inputs.size(0)\n",
                "        scheduler.step()\n",
                "        \n",
                "        model.eval()\n",
                "        correct, total = 0, 0\n",
                "        with torch.no_grad():\n",
